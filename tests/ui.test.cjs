const {test}=require('node:test');const assert=require('node:assert/strict');
const {_electron:electron}=require('playwright');
const {mkdtempSync,rmSync,mkdirSync}=require('node:fs');const {join,resolve}=require('node:path');const {tmpdir}=require('node:os');
test('desktop workflows: IME, edit, external updates, undo, sorting and compact bounds', {timeout:60000},async t=>{
  const root=mkdtempSync(join(tmpdir(),'pocket-ui-')),dir=join(root,'first-run');
  const env={...process.env,POCKET_TODO_DATA_DIR:dir};delete env.ELECTRON_RUN_AS_NODE;
  const app=await electron.launch({args:[resolve('.')],env});
  t.after(async()=>{await app.close();rmSync(root,{recursive:true,force:true});});
  const page=await app.firstWindow();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.locator('#new-title').fill('第一条中文任务');
  await page.locator('#new-title').press('Enter');
  await page.getByRole('button',{name:'第一条中文任务',exact:true}).waitFor({timeout:4000});
  await page.locator('#new-title').fill('输入法待确认');
  await page.locator('#new-title').evaluate(el=>el.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true,cancelable:true})));
  assert.equal(await page.locator('.task-row').count(),1);
  await page.locator('#new-title').fill('第二条任务');await page.locator('#new-title').press('Enter');
  await page.getByRole('button',{name:'第二条任务',exact:true}).waitFor();
  await page.getByRole('button',{name:'第一条中文任务',exact:true}).click();
  await page.locator('#edit-status').selectOption('pending');await page.locator('#edit-date').click();
  await page.locator('#calendar-today').click();
  await page.getByRole('button',{name:'Save changes'}).click();
  await page.getByRole('button',{name:'Pending',exact:true}).click();
  await page.getByRole('button',{name:'第一条中文任务',exact:true}).waitFor();
  await page.locator('.task-check').check();
  await page.getByRole('button',{name:'Completed',exact:true}).click();
  await page.getByRole('button',{name:'第一条中文任务',exact:true}).waitFor();
  await page.locator('.task-cancel').click();await page.getByRole('button',{name:'Cancelled',exact:true}).click();
  await page.locator('.task-delete').click();await page.locator('#undo').click();
  await page.getByRole('button',{name:'第一条中文任务',exact:true}).waitFor();
  await page.getByRole('button',{name:'To-do',exact:true}).click();
  await page.locator('#new-title').fill('还没输入完');
  const {createStore}=require('../src/store.cjs');const external=createStore(join(dir,'todos.sqlite'));
  external.add({title:'AI 添加的任务',category:'content'});external.close();
  await page.getByRole('button',{name:'AI 添加的任务',exact:true}).waitFor({timeout:5000});
  assert.equal(await page.locator('#new-title').inputValue(),'还没输入完');
  await page.locator('#new-title').fill('');await page.locator('#connections').click();
  await page.locator('#connection-dialog').waitFor({state:'visible'});
  assert.match(await page.locator('#config-content').inputValue(),/mcp_servers.pocket-todo/);
  await page.getByRole('button',{name:'关闭连接器'}).click();
  mkdirSync(resolve('screenshots'),{recursive:true});
  await page.screenshot({path:resolve('screenshots/desktop.png')});
  await page.locator('#collapse').click();
  await page.waitForFunction(()=>document.body.classList.contains('is-collapsed'));
  assert.equal((await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].getBounds())).width,88);
  assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].isAlwaysOnTop()),true);
  await page.screenshot({path:resolve('screenshots/collapsed.png')});
  assert.deepEqual(errors,[]);
});
